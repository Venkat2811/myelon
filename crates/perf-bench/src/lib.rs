//! Shared benchmark infrastructure for the `disruptor-mp` and
//! `myelon` transport stack. **Internal — not published to
//! crates.io.**
//!
//! Provides multiprocess coordination, event types, payload generators,
//! and reporting utilities consumed by:
//!
//! - `perf-bench-pingpong` — 1p1c ping-pong over `raw_ring`,
//!   `raw_myelon`, `framed`, `codec`, `typed_zc` layers and
//!   `shm` / `mmap` backends.
//! - `perf-bench-broadcast` — 1pNc broadcast.
//! - `perf-bench-repeatability` — repeated-run variance harness.
//! - `perf-bench-signal` — signal-only ring scenarios.
//!
//! Modules:
//!
//! - [`cli`] — flag definitions for each consolidated binary.
//! - [`infra`] — multiprocess coordination, latency recorders,
//!   reporting.
//! - [`layers`] — per-layer benchmark code (raw, framed, codec, typed
//!   zero-copy).
//! - [`bench_support`] — shared event types, competitor reference data,
//!   and helper functions consumed via `#[path]` by per-layer modules
//!   and by `competitive-bench`'s adapter binaries.

pub mod bench_support;
pub mod cli;
pub mod env;
pub mod infra;
pub mod layers;

